def date(s):
    """1991年10月11日 → 1991.10.11 · 1991年10月 → 1991.10"""
    s = s.translate(DIG)
    return re.sub(r'(\d+)年(\d+)月(?:(\d+)日)?', lambda m: '.'.join(x for x in m.groups() if x), s)


def line(l):
    t = l.translate(DIG)
    if t in ('JAL', 'JTA', 'JEX'):
        return t
    m = re.match(r'^([A-Z0-9/\-]+)(?:「(.+)」)?$', t.replace('ー', '-'))
    if m and '/' in t:
        nm = m.group(2)
        if nm:
            nm0 = l[l.index('「') + 1:l.index('」')]
            return '%s「%s」' % (m.group(1), NAMES[nm0])
        return m.group(1)
    if t.startswith('製造番号'):
        return '제조번호 ' + t[4:]
    if t in ('中短距離仕様', '長距離仕様'):
        return {'中短距離仕様': '중단거리 사양', '長距離仕様': '장거리 사양'}[t]
    m = re.match(r'^(\d)代目マーキング・(.*)$', t)
    if m:
        rest = line(m.group(2)) if m.group(2) else ''
        return '%s세대 도장.%s' % (m.group(1), rest)
    if '登録抹消' in t:
        a, b = t.split('〜')
        return '%s 등록~%s 말소' % (date(a.replace('登録', '')), date(b.replace('登録抹消', '')))
    if t.endswith('登録'):
        return date(t[:-2]) + ' 등록'
    m = re.match(r'^(?:(.+?)に)?(JALエクスブレス|JALウェイズ|日本アジア航空)に移管$', t)
    if m:
        to = {'JALエクスブレス': 'JAL 익스프레스로', 'JALウェイズ': 'JAL 웨이즈로', '日本アジア航空': '일본아시아항공으로'}[m.group(2)]
        return ('%s %s 이관' % (date(m.group(1)), to)) if m.group(1) else '%s 이관' % to
    m = re.match(r'^(?:(.+?)に)?日本航空から転籍$', t)
    if m:
        return ('%s 일본항공에서 전적' % date(m.group(1))) if m.group(1) else '일본항공에서 전적'
    raise ValueError(l)


